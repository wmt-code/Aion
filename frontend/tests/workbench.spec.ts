import { expect, test } from '@playwright/test'

test('通用任务画布支持按需审阅、键盘访问和草稿保留', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '今天，想完成什么？' })).toBeVisible()
  expect(await page.locator('body').evaluate((element) => getComputedStyle(element).fontFamily)).toContain('Segoe UI')
  await expect(page.getByRole('complementary', { name: '产物审阅' })).not.toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('initial.png'), fullPage: true })
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: '跳转到工作区' })).toBeFocused()
  await expect(page.getByRole('button', { name: /了解项目|实现功能|排查问题/ })).toHaveCount(0)
  const draft = page.getByRole('textbox', { name: '任务描述' })
  await expect(draft).toHaveAttribute('placeholder', '描述你的目标，或从一个问题开始…')
  await draft.fill('整理这份资料，归纳关键结论和仍需核实的信息。')
  await page.getByLabel('任务模式').selectOption('execute')
  await expect(page.getByRole('button', { name: '发送', exact: true })).toBeDisabled()

  const width = page.viewportSize()?.width ?? 1440
  if (width < 1280) {
    await page.getByRole('button', { name: '打开导航' }).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await expect(page.getByRole('button', { name: '新建会话' })).toBeDisabled()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).not.toBeVisible()
    await expect(page.getByRole('button', { name: '打开导航' })).toBeFocused()
  } else {
    await page.getByRole('button', { name: '收起导航' }).click()
    await expect(page.getByRole('navigation', { name: '会话导航' })).not.toBeVisible()
    await page.getByRole('button', { name: '展开导航' }).click()
    await expect(page.getByRole('navigation', { name: '会话导航' })).toBeVisible()
  }
  await page.getByRole('button', { name: '展开产物面板' }).click()
  await expect(page.getByRole('complementary', { name: '产物审阅' })).toBeFocused()
  if (width < 768) await expect(draft).not.toBeVisible()
  await page.getByRole('tab', { name: '成果', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: '文件' })).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: '变更' })).toBeFocused()
  await expect(page.getByRole('heading', { name: '暂无变更' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('inspector.png'), fullPage: true })
  await page.getByRole('button', { name: '返回任务' }).click()
  await expect(page.getByRole('button', { name: '展开产物面板' })).toBeFocused()
  await expect(draft).toHaveValue('整理这份资料，归纳关键结论和仍需核实的信息。')
  await expect(page.getByLabel('任务模式')).toHaveValue('execute')

  const initialTheme = testInfo.project.use.colorScheme === 'dark' ? 'dark' : 'light'
  await expect(page.locator('.app-shell')).toHaveAttribute('data-theme', initialTheme)
  await page.getByRole('button', { name: initialTheme === 'dark' ? '切换浅色主题' : '切换深色主题' }).click()
  await expect(page.locator('.app-shell')).toHaveAttribute('data-theme', initialTheme === 'dark' ? 'light' : 'dark')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(draft).toBeInViewport()
  expect(errors).toEqual([])
  await page.screenshot({ path: testInfo.outputPath('workbench.png'), fullPage: true })
})

test('短视口和长任务仍可操作', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 480 })
  await page.emulateMedia({ reducedMotion: 'reduce', contrast: 'more' })
  await page.goto('/')
  const draft = page.getByRole('textbox', { name: '任务描述' })
  const content = '这是需要分析的背景信息。'.repeat(500)
  await draft.fill(content)
  await expect(draft).toHaveValue(content)
  await page.getByLabel('任务模式').selectOption('execute')
  await page.getByRole('button', { name: '发送', exact: true }).scrollIntoViewIfNeeded()
  await expect(page.getByRole('button', { name: '发送', exact: true })).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: '展开产物面板' }).click()
  await page.getByRole('button', { name: '返回任务' }).click()
  await expect(draft).toHaveValue(content)
})
